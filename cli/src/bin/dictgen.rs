//! Generate the `dictionary` tables from the DICOM PS3.6 DocBook source.
//!
//! Usage:
//!
//! ```text
//! cargo run -p dcm4rs-cli --bin dictgen -- data/part06.xml dcm4rs/src/dictionary/generated.rs
//! ```

use std::collections::{BTreeMap, HashSet};
use std::fmt::Write as _;
use std::fs;

fn main() {
    if let Err(error) = run() {
        eprintln!("dictgen: {error}");
        std::process::exit(1);
    }
}

fn run() -> Result<(), Box<dyn std::error::Error>> {
    let mut args = std::env::args().skip(1);
    let input = args.next().unwrap_or_else(|| "data/part06.xml".to_owned());
    let output = args
        .next()
        .unwrap_or_else(|| "dcm4rs/src/dictionary/generated.rs".to_owned());

    let xml = fs::read_to_string(&input)?;
    let rows = extract_rows(&xml);
    let columns = find_columns(&rows).ok_or_else(|| {
        std::io::Error::new(
            std::io::ErrorKind::InvalidData,
            "no table header with Tag/Name/Keyword/VR/VM found",
        )
    })?;

    let mut exact: BTreeMap<u32, EntryData> = BTreeMap::new();
    let mut repeaters: BTreeMap<(u32, u32), EntryData> = BTreeMap::new();
    let mut skipped = 0usize;
    let mut replaced = 0usize;

    for cells in &rows {
        if cells.len() <= columns.vm {
            continue;
        }
        let Some((mask, value)) = parse_tag_cell(&cells[columns.tag]) else {
            continue;
        };
        let name = clean(&cells[columns.name]);
        let keyword = clean(&cells[columns.keyword]);
        let vr_text = clean(&cells[columns.vr]);
        let vm = clean(&cells[columns.vm]);
        if name.is_empty() || vr_text.is_empty() {
            skipped += 1;
            continue;
        }
        let Some(vr) = vr_expr(&vr_text) else {
            eprintln!("skipping unrecognized VR: {vr_text:?} ({name})");
            skipped += 1;
            continue;
        };

        let retired = columns
            .desc
            .and_then(|index| cells.get(index))
            .is_some_and(|text| clean(text).eq_ignore_ascii_case("RET"))
            || name.ends_with("(Retired)");

        let data = EntryData {
            name: strip_retired(&name),
            keyword,
            vr,
            vm,
            retired,
        };

        if mask == 0xFFFF_FFFF {
            if exact.insert(value, data).is_some() {
                replaced += 1;
            }
        } else {
            repeaters.insert((mask, value), data);
        }
    }

    let mut out = String::with_capacity(1_500_000);
    writeln!(
        out,
        "// Generated by `dictgen` from the DICOM PS3.6 source; do not edit by hand."
    )?;
    writeln!(
        out,
        "// Source: DICOM PS3.6 Chapter 6, Registry of DICOM Data Elements."
    )?;
    writeln!(out)?;
    writeln!(out, "use crate::{{Tag, Vr}};")?;
    writeln!(out)?;
    writeln!(out, "use super::{{Entry, Repeater, VrDef}};")?;
    writeln!(out)?;

    writeln!(
        out,
        "/// All standard data elements, in ascending tag order."
    )?;
    writeln!(out, "#[rustfmt::skip]")?;
    writeln!(out, "pub(crate) static ENTRIES: &[Entry] = &[")?;
    for (raw, entry) in &exact {
        write_entry(&mut out, *raw, entry)?;
    }
    writeln!(out, "];")?;
    writeln!(out)?;

    writeln!(out, "/// Repeating-group entries, e.g. (60xx,0010).")?;
    writeln!(out, "#[rustfmt::skip]")?;
    writeln!(out, "pub(crate) static REPEATERS: &[Repeater] = &[")?;
    for ((mask, value), entry) in &repeaters {
        let (mask, value) = (*mask, *value);
        writeln!(
            out,
            "    Repeater {{ mask: {mask:#010X}, value: {value:#010X}, entry: Entry {{ tag: Tag::new({:#06X}, {:#06X}), keyword: {:?}, name: {:?}, vr: {}, vm: {:?}, retired: {} }} }},",
            (value >> 16) as u16,
            (value & 0xFFFF) as u16,
            entry.keyword,
            entry.name,
            entry.vr,
            entry.vm,
            entry.retired
        )?;
    }
    writeln!(out, "];")?;
    writeln!(out)?;

    writeln!(
        out,
        "/// Tag constants for standard data elements, named after their uppercased keyword."
    )?;
    writeln!(out, "#[rustfmt::skip]")?;
    writeln!(out, "pub mod tags {{")?;
    writeln!(out, "    use crate::Tag;")?;
    writeln!(out)?;
    let mut constants = HashSet::new();
    for (raw, entry) in &exact {
        let Some(ident) = const_name(&entry.keyword) else {
            continue;
        };
        if !constants.insert(ident.clone()) {
            continue;
        }
        if entry.retired {
            writeln!(out, "    /// {} (retired)", doc_text(&entry.name))?;
        } else {
            writeln!(out, "    /// {}", doc_text(&entry.name))?;
        }
        writeln!(
            out,
            "    pub const {ident}: Tag = Tag::new({:#06X}, {:#06X});",
            (*raw >> 16) as u16,
            (*raw & 0xFFFF) as u16
        )?;
    }
    writeln!(out, "}}")?;

    fs::write(&output, out)?;
    eprintln!(
        "generated {} standard elements ({} overridden, {} skipped, {} tag constants) and {} repeating groups",
        exact.len(),
        replaced,
        skipped,
        constants.len(),
        repeaters.len()
    );
    Ok(())
}

#[derive(Clone, Debug)]
struct EntryData {
    name: String,
    keyword: String,
    vr: String,
    vm: String,
    retired: bool,
}

#[derive(Clone, Copy, Debug)]
struct Columns {
    tag: usize,
    name: usize,
    keyword: usize,
    vr: usize,
    vm: usize,
    desc: Option<usize>,
}

fn write_entry(out: &mut String, raw: u32, entry: &EntryData) -> std::fmt::Result {
    writeln!(
        out,
        "    Entry {{ tag: Tag::new({:#06X}, {:#06X}), keyword: {:?}, name: {:?}, vr: {}, vm: {:?}, retired: {} }},",
        (raw >> 16) as u16,
        (raw & 0xFFFF) as u16,
        entry.keyword,
        entry.name,
        entry.vr,
        entry.vm,
        entry.retired
    )
}

fn find_columns(rows: &[Vec<String>]) -> Option<Columns> {
    for cells in rows {
        if cells.len() < 5 {
            continue;
        }
        let find = |needle: &str| {
            cells
                .iter()
                .position(|cell| cell.eq_ignore_ascii_case(needle))
        };
        if let (Some(tag), Some(name), Some(keyword), Some(vr), Some(vm)) = (
            find("Tag"),
            find("Name"),
            find("Keyword"),
            find("VR"),
            find("VM"),
        ) {
            let desc = if vm + 1 < cells.len() {
                Some(vm + 1)
            } else {
                None
            };
            return Some(Columns {
                tag,
                name,
                keyword,
                vr,
                vm,
                desc,
            });
        }
    }
    None
}

/// Parse a cell such as `(0010,0010)` or `(60xx,0010)`, returning `(mask, value)`.
fn parse_tag_cell(text: &str) -> Option<(u32, u32)> {
    let compact: String = text
        .chars()
        .filter(|ch| !ch.is_whitespace() && !is_invisible(*ch))
        .collect();
    let inner = compact.strip_prefix('(')?.strip_suffix(')')?;
    let (group, element) = inner.split_once(',')?;
    if group.len() != 4 || element.len() != 4 {
        return None;
    }
    let (group_mask, group_value) = nibbles(group)?;
    let (element_mask, element_value) = nibbles(element)?;
    Some((
        (group_mask as u32) << 16 | element_mask as u32,
        (group_value as u32) << 16 | element_value as u32,
    ))
}

/// Split four hex characters (possibly containing `x`) into (mask, value).
fn nibbles(text: &str) -> Option<(u16, u16)> {
    let mut mask = 0u16;
    let mut value = 0u16;
    for (index, ch) in text.chars().enumerate() {
        if index > 3 {
            return None;
        }
        let shift = 4 * (3 - index) as u16;
        if let Some(digit) = ch.to_digit(16) {
            mask |= 0xF << shift;
            value |= (digit as u16) << shift;
        } else if ch != 'x' && ch != 'X' {
            return None;
        }
    }
    Some((mask, value))
}

/// Turn a VR cell such as `"US or SS"` into a Rust expression.
///
/// VR validity is decided by the library itself; this tool keeps no second VR list.
fn vr_expr(text: &str) -> Option<String> {
    let mut variants = Vec::new();
    for part in text.split(" or ") {
        let vr: dcm4rs::Vr = part.trim().parse().ok()?;
        variants.push(format!("Vr::{vr:?}"));
    }
    match variants.as_slice() {
        [] => None,
        [only] => Some(format!("VrDef::Fixed({only})")),
        many => Some(format!("VrDef::Ambiguous(&[{}])", many.join(", "))),
    }
}

/// `PatientName` -> `PATIENT_NAME`; `RTPatientName` -> `RT_PATIENT_NAME`.
fn const_name(keyword: &str) -> Option<String> {
    if keyword.is_empty()
        || !keyword.chars().all(|ch| ch.is_ascii_alphanumeric())
        || !keyword.starts_with(|ch: char| ch.is_ascii_alphabetic())
    {
        return None;
    }

    let chars: Vec<char> = keyword.chars().collect();
    let mut out = String::with_capacity(keyword.len() * 2);
    for (index, ch) in chars.iter().enumerate() {
        if ch.is_ascii_uppercase() && index > 0 {
            let previous = chars[index - 1];
            let next_is_lower = chars.get(index + 1).is_some_and(char::is_ascii_lowercase);
            if previous.is_ascii_lowercase()
                || previous.is_ascii_digit()
                || (previous.is_ascii_uppercase() && next_is_lower)
            {
                out.push('_');
            }
        }
        out.push(ch.to_ascii_uppercase());
    }
    Some(out)
}

fn strip_retired(name: &str) -> String {
    match name.strip_suffix("(Retired)") {
        Some(prefix) => prefix.trim().to_owned(),
        None => name.to_owned(),
    }
}

fn doc_text(name: &str) -> String {
    name.replace('\n', " ")
}

fn is_invisible(ch: char) -> bool {
    matches!(ch, '\u{200B}' | '\u{200C}' | '\u{200D}' | '\u{FEFF}')
}

/// Strip zero-width characters and redundant whitespace (the official DocBook inserts U+200B in
/// keywords).
fn clean(text: &str) -> String {
    let mut removed = String::with_capacity(text.len());
    for ch in text.chars() {
        match ch {
            '\u{00A0}' => removed.push(' '),
            _ if is_invisible(ch) => {}
            _ => removed.push(ch),
        }
    }
    removed.split_whitespace().collect::<Vec<_>>().join(" ")
}

fn extract_rows(xml: &str) -> Vec<Vec<String>> {
    let mut rows = Vec::new();
    let mut rest = xml;
    while let Some(position) = rest.find("<tr") {
        let tail = &rest[position..];
        let after_tag = &tail[3..];
        let is_row =
            after_tag.starts_with('>') || after_tag.starts_with(|ch: char| ch.is_whitespace());
        if !is_row {
            rest = after_tag;
            continue;
        }
        let Some(end) = tail.find("</tr>") else {
            break;
        };
        let cells = cell_texts(&tail[..end]);
        if cells.len() >= 5 {
            rows.push(cells);
        }
        rest = &tail[end + "</tr>".len()..];
    }
    rows
}

fn cell_texts(row: &str) -> Vec<String> {
    for name in ["td", "th"] {
        let cells = collect_cells(row, name);
        if !cells.is_empty() {
            return cells;
        }
    }
    Vec::new()
}

fn collect_cells(row: &str, name: &str) -> Vec<String> {
    let mut out = Vec::new();
    let close = format!("</{name}>");
    let mut rest = row;
    while let Some(position) = find_open_tag(rest, name) {
        let after = &rest[position..];
        let Some(gt) = after.find('>') else {
            break;
        };
        let body = &after[gt + 1..];
        let Some(end) = body.find(&close) else {
            break;
        };
        out.push(normalize(&body[..end]));
        rest = &body[end + close.len()..];
    }
    out
}

fn find_open_tag(text: &str, name: &str) -> Option<usize> {
    let needle = format!("<{name}");
    let mut offset = 0;
    while let Some(position) = text[offset..].find(&needle) {
        let absolute = offset + position;
        let after = &text[absolute + needle.len()..];
        if after.starts_with('>') || after.starts_with(|ch: char| ch.is_whitespace()) {
            return Some(absolute);
        }
        offset = absolute + needle.len();
    }
    None
}

fn normalize(text: &str) -> String {
    clean(&unescape(&strip_tags(text)))
}

fn strip_tags(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut inside = false;
    for ch in text.chars() {
        match ch {
            '<' => inside = true,
            '>' => inside = false,
            _ if !inside => out.push(ch),
            _ => {}
        }
    }
    out
}

fn unescape(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut rest = text;
    while let Some(position) = rest.find('&') {
        out.push_str(&rest[..position]);
        let tail = &rest[position..];
        let Some(end) = tail.find(';') else {
            out.push_str(tail);
            return out;
        };
        let entity = &tail[1..end];
        match entity {
            "amp" => out.push('&'),
            "lt" => out.push('<'),
            "gt" => out.push('>'),
            "quot" => out.push('"'),
            "apos" => out.push('\''),
            "nbsp" => out.push(' '),
            _ if entity.starts_with("#x") || entity.starts_with("#X") => {
                if let Ok(code) = u32::from_str_radix(&entity[2..], 16) {
                    if let Some(ch) = char::from_u32(code) {
                        out.push(ch);
                    }
                }
            }
            _ if entity.starts_with('#') => {
                if let Ok(code) = entity[1..].parse::<u32>() {
                    if let Some(ch) = char::from_u32(code) {
                        out.push(ch);
                    }
                }
            }
            _ => {
                out.push('&');
                out.push_str(entity);
                out.push(';');
            }
        }
        rest = &tail[end + 1..];
    }
    out.push_str(rest);
    out
}
