#!/usr/bin/env python3
"""Generate the PS3.6 UID registry table from pydicom's ``_uid_dict.py``.

pydicom carries the registry as ``UID_dictionary = {uid: (name, type, info, retired, keyword)}``.
This script reads that dictionary and writes the same data as a Rust static, sorted by UID so
the lookup can binary search it.

Usage:
    python tools/gen_uid.py path/to/pydicom/_uid_dict.py > dcm4rs/src/uid/generated.rs
"""

import ast
import json
import sys
from pathlib import Path


def load_dictionary(source: Path) -> dict:
    tree = ast.parse(source.read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(
            getattr(target, "id", "") == "UID_dictionary" for target in node.targets
        ):
            return ast.literal_eval(node.value)
    raise SystemExit(f"no UID_dictionary assignment found in {source}")


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    entries = load_dictionary(Path(sys.argv[1]))

    print("// Generated by tools/gen_uid.py from pydicom's _uid_dict.py; do not edit by hand.")
    print("// Each entry is the PS3.6 registry row: UID, name, type, info, retired, keyword.")
    print()
    print("/// One row of the PS3.6 UID registry.")
    print("pub struct Entry {")
    print("    /// The UID value.")
    print("    pub uid: &'static str,")
    print("    /// The registry name, such as `Implicit VR Little Endian`.")
    print("    pub name: &'static str,")
    print("    /// The registry type, such as `Transfer Syntax` or `SOP Class`.")
    print("    pub kind: &'static str,")
    print("    /// Additional registry information; empty for most entries.")
    print("    pub info: &'static str,")
    print("    /// Whether the UID is retired.")
    print("    pub retired: bool,")
    print("    /// The DICOM keyword, such as `ImplicitVRLittleEndian`.")
    print("    pub keyword: &'static str,")
    print("}")
    print()
    print("/// All registry entries, in ascending UID order for binary search.")
    print("#[rustfmt::skip]")
    print("pub(crate) static ENTRIES: &[Entry] = &[")
    for uid in sorted(entries):
        name, kind, info, retired, keyword = entries[uid]
        retired_flag = "true" if retired else "false"
        print(
            f"    Entry {{ uid: {json.dumps(uid)}, name: {json.dumps(name)}, "
            f"kind: {json.dumps(kind)}, info: {json.dumps(info)}, "
            f"retired: {retired_flag}, keyword: {json.dumps(keyword)} }},"
        )
    print("];")


if __name__ == "__main__":
    main()
