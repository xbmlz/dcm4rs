#!/usr/bin/env python3
"""Generate the JIS X 0212 mapping table used by ISO 2022 IR 159.

Python's ``iso2022_jp_2`` codec carries the JIS X 0212 table. This script walks
every 94x94 code point and writes the JIS code -> Unicode scalar mapping as a
Rust static table, sorted by code so the decoder can binary search it.

Usage:
    python tools/gen_jis0212.py > dcm4rs/src/jis0212.rs
"""

ESC = bytes([0x1B, 0x24, 0x28, 0x44])  # ESC $ ( D: designate JIS X 0212 to G0


def main() -> None:
    print("// Generated by tools/gen_jis0212.py from Python's iso2022_jp_2 codec.")
    print("// JIS X 0212 (ISO 2022 IR 159): JIS code -> Unicode scalar.")
    print("// Sorted by code for binary search; unused cells are omitted.")
    print("pub(crate) static JIS_X_0212: &[(u16, char)] = &[")
    for row in range(0x21, 0x7F):
        cells = []
        for cell in range(0x21, 0x7F):
            try:
                text = (ESC + bytes([row, cell])).decode("iso2022_jp_2")
            except UnicodeDecodeError:
                continue
            if len(text) != 1:
                continue
            code = (row << 8) | cell
            cells.append(f"(0x{code:04X}, '\\u{{{ord(text):04X}}}')")
        if cells:
            print("    " + ", ".join(cells) + ",")
    print("];")


if __name__ == "__main__":
    main()
